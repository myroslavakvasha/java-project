    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedPhotographer == null) {
            MessageUtils.showInformationMessage("Wrong operation", "Please choose a photographer to delete");
            return;
        }
        if (MessageUtils.showConfirmDialog(
                "Delete photographer",
                "Do you really want to delete photographer?")) {
            try {
                repository.deletePhotographer(selectedPhotographer.getId());
                photographersTableModel.setItems(repository.selectPhotographers());
                clearForm();
            } catch (Exception ex) {
                Logger.getLogger(PhotographersPanel.class.getName()).log(Level.SEVERE, null, ex);
                MessageUtils.showErrorMessage("Error", "Unable to delete photographer!");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (!formValid()) {
            return;
        }
        try {
            Photographer photographer = new Photographer(tfName.getText().trim(), tfSurname.getText().trim());
            repository.createPhotographer(photographer);
            photographersTableModel.setItems(repository.selectPhotographers());
            clearForm();
        } catch (Exception ex) {
            Logger.getLogger(PhotographersPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to create photographer!");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedPhotographer == null) {
            MessageUtils.showInformationMessage("Wrong operation", "Please choose a photographer to update");
            return;
        }
        if (!formValid()) {
            return;
        }
        try {
            selectedPhotographer.setName(tfName.getText().trim());
            selectedPhotographer.setSurname(tfSurname.getText().trim());
            repository.updatePhotographer(selectedPhotographer.getId(), selectedPhotographer);
            photographersTableModel.setItems(repository.selectPhotographers());
            clearForm();
        } catch (Exception ex) {
            Logger.getLogger(PhotographersPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to update photographer!");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

