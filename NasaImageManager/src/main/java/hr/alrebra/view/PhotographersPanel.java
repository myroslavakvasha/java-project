    private void showPhotographer() {
        clearForm();
        int selectedRow = tbPhotographers.getSelectedRow();
        int rowIndex = tbPhotographers.convertRowIndexToModel(selectedRow);
        int selectedPhotographerId = (int) photographersTableModel.getValueAt(rowIndex, 0);

        try {
            Optional<Photographer> optPhotographer = repository.selectPhotographer(selectedPhotographerId);
            if (optPhotographer.isPresent()) {
                selectedPhotographer = optPhotographer.get();
                fillForm(selectedPhotographer);
            }
        } catch (Exception ex) {
            Logger.getLogger(PhotographersPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to show photographer!");
        }
    }

    private void clearForm() {
        hideErrors();
        validationFields.forEach(e -> e.setText(""));
        selectedPhotographer = null;
    }

    private boolean formValid() {
        hideErrors();
        boolean ok = true;

        for (int i = 0; i < validationFields.size(); i++) {
            ok &= !validationFields.get(i).getText().trim().isEmpty();
            errorLabels.get(i).setVisible(validationFields.get(i).getText().trim().isEmpty());
        }
        return ok;
    }

    private void hideErrors() {
        errorLabels.forEach(e -> e.setVisible(false));
    }

    private void init() {
        try {
            initValidation();
            hideErrors();
            initRepository();
            initTable();
        } catch (Exception ex) {
            Logger.getLogger(PhotographersPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Unrecoverable error", "Cannot initiate the form");
            System.exit(1);
        }
    }

    private void initValidation() {
        validationFields = Arrays.asList(tfName, tfSurname);
        errorLabels = Arrays.asList(lbErrorName, lbErrorSurname);
    }

    private void initRepository() throws Exception {
        repository = RepositoryFactory.getRepository();
    }

    private void initTable() throws Exception {
        tbPhotographers.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tbPhotographers.setAutoCreateRowSorter(true);
        tbPhotographers.setRowHeight(25);
        photographersTableModel = new PhotographerTableModel(repository.selectPhotographers());
        tbPhotographers.setModel(photographersTableModel);
    }

    private void fillForm(Photographer photographer) {
        tfName.setText(photographer.getName());
        tfSurname.setText(photographer.getSurname());
    }
