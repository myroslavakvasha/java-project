    private DefaultListModel<NasaImage> nasaImagesModel;
    private Repository repository;

    private void init() {
        try {
            repository = RepositoryFactory.getRepository();
            nasaImagesModel = new DefaultListModel<>();
            loadModel();
        } catch (Exception ex) {
            Logger.getLogger(UploadPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Unrecoverable error", "Cannot initiate the form");
            //System.exit(1); // app creshes no can do!
        }
    }

    private void loadModel() throws Exception {
        List<NasaImage> images = repository.selectNasaImages();
        nasaImagesModel.clear();
        images.forEach(nasaImagesModel::addElement);
        lsImages.setModel(nasaImagesModel);
    }

