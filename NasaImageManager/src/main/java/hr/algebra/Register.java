    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        String username = tfUsername.getText().trim();
        String password = new String(pfPassword.getPassword());
        String passwordComfirmed = new String(pfRepeatPassword.getPassword());

        Optional<User> userOptional;
        try {
            userOptional = repository.selectUserByUsername(username);
            if (userOptional.isPresent()) {
                MessageUtils.showErrorMessage("Registration failed", "Username already exists");
                return;
            }
            if (!password.equals(passwordComfirmed)) {
                MessageUtils.showErrorMessage("Registration failed", "Passwords don't match");
                return;
            }

            String passwordHash = PasswordUtils.hashPassword(password);
            repository.createUser(new User(username, passwordHash, Role.USER));
            MessageUtils.showInformationMessage("Success", "Account created! Please log in");
            
            new Login().setVisible(true);
            this.dispose();
        } catch (Exception ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Registration failed", "Could not create new user");
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

