    private void configurePanels(User user) {
        if (user.getRole() == Role.ADMIN) {
            tpContent.add("Upload", new UploadPanel());
        } else {
            tpContent.add("NASA Images", new NasaImagesPanel());
            tpContent.add("Categories", new CategoriesPanel());
            tpContent.add("Missions", new MissionsPanel());
            tpContent.add("Photographers", new PhotographersPanel());
            tpContent.add("Image Categories", new ImageCategoriesPanel());
        }
    }

    private void configureMenu(User user) {
        // hide Tools menu for admin — they don't need XML export
        mTools.setVisible(user.getRole() == Role.USER);

        miLogout.addActionListener(e -> logout());
        miExport.addActionListener(e -> exportXml());
    }

    private void logout() {
        new Login().setVisible(true);
        this.dispose();
    }

    private void exportXml() {
        File file = FileUtils.saveFile("XML Files", "xml");
        if (file != null) {
            try {
                Repository repo = RepositoryFactory.getRepository();
                List<NasaImageExportDto> dtos = repo.selectNasaImagesForExport();
                JAXBUtils.marshal(new NasaImageExportList(dtos), file.getAbsolutePath());
                MessageUtils.showInformationMessage("Export", "Export successful!");
            } catch (Exception e) {
                MessageUtils.showErrorMessage("Export", "Export failed: " + e.getMessage());
            }
        }
    }
